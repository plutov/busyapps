func makeXPM(text string) (string, error) {
	letters := []rune(text)
	for _, letter := range letters {
		if letter != ' ' && glyphs[letter] == nil {
			return "", fmt.Errorf("unsupported character %q", letter)
		}
	}
	scale := 1
	if textWidth(letters, 2) <= 66 {
		scale = 2
	}
	contentWidth := textWidth(letters, scale)
	if contentWidth+1 > width {
		return "", fmt.Errorf("text is too wide: %q", text)
	}
	pixels := background()
	x := (width - contentWidth) / 2
	y := (height - (7*scale + 1)) / 2
	for _, letter := range letters {
		if letter == ' ' {
			x += 3 * scale
			continue
		}
		paintGlyph(pixels, glyphs[letter], x+1, y+1, scale, '#')
		paintGlyph(pixels, glyphs[letter], x, y, scale, '*')
		x += 6 * scale
	}
	lines := []string{
		"! XPM2",
		"72 16 5 1",
		". c #11111b",
		"- c #1e1e2e",
		"+ c #313244",
		"# c #f38ba8",
		"* c #f5e0dc",
	}
	for _, row := range pixels {
		lines = append(lines, string(row))
	}
	return strings.Join(lines, "\n"), nil
}

func textWidth(letters []rune, scale int) int {
	width := 0
	for _, letter := range letters {
		if letter == ' ' {
			width += 3 * scale
		} else {
			width += 6 * scale
		}
	}
	return width - scale
}

func background() [][]byte {
	pixels := make([][]byte, height)
	for y := range pixels {
		pixels[y] = make([]byte, width)
		for x := range pixels[y] {
			pixel := byte('.')
			if y%4 == 0 {
				pixel = '-'
			}
			if (x*3+y*5)%17 == 0 {
				pixel = '+'
			}
			pixels[y][x] = pixel
		}
	}
	return pixels
}

func paintGlyph(pixels [][]byte, glyph []string, x, y, scale int, color byte) {
	for row, line := range glyph {
		for column, value := range line {
			if value != '1' {
				continue
			}
			for dy := range scale {
				for dx := range scale {
					px, py := x+column*scale+dx, y+row*scale+dy
					if px >= 0 && px < width && py >= 0 && py < height {
						pixels[py][px] = color
					}
				}
			}
		}
	}
}

func printBanner(text string) {
	colors := map[byte]string{
		'.': "17;17;27", '-': "30;30;46", '+': "49;50;68", '#': "243;139;168", '*': "245;224;220",
	}
	xpm, _ := makeXPM(text)
	for _, line := range strings.Split(xpm, "\n")[7:] {
		for _, pixel := range []byte(line) {
			fmt.Printf("\x1b[48;2;%sm  ", colors[pixel])
		}
		fmt.Print("\x1b[0m\n")
	}
}
